const { test } = require('node:test');
const assert = require('node:assert/strict');
test('regional suggestions use selected country and city with separate mode caches', async t => {
  const sdkPath = require.resolve('@google/genai');
  const sdk = require('@google/genai');
  const key = process.env.GEMINI_API_KEY;
  const prompts = [];
  require.cache[sdkPath].exports = { ...sdk, GoogleGenAI: class {
    models = { generateContent: async ({ contents }) => {
      prompts.push(contents);
      const place = contents.includes('Vietnam') ? 'Vietnam' : 'Japan';
      return { text: JSON.stringify({ songs: [{ title: `${place} song`, artist: `${place} artist`, year: 2000, reason: `Local to ${place}` }] }) };
    } };
  } };
  delete require.cache[require.resolve('../services/nostalgia')];
  t.after(() => { require.cache[sdkPath].exports = sdk; if (key === undefined) delete process.env.GEMINI_API_KEY; else process.env.GEMINI_API_KEY = key; });
  process.env.GEMINI_API_KEY = 'test';
  const { getRegionalSongs, getNostalgia } = require('../services/nostalgia');
  const vietnam = await getRegionalSongs('Vietnam', 'Hanoi');
  const japan = await getRegionalSongs('Japan', 'Tokyo');
  assert.notDeepEqual(vietnam.songs, japan.songs);
  assert.equal(vietnam.chartArea, 'Hanoi');
  assert.equal(japan.chartArea, 'Tokyo');
  assert.equal(japan.kind, 'regional');
  assert.match(prompts[0], /Hanoi/);
  assert.match(prompts[1], /Tokyo/);
  await getRegionalSongs('Japan', 'Tokyo');
  assert.equal(prompts.length, 2);
  const old = await getNostalgia('Japan', 'Tokyo');
  assert.equal(old.kind, 'nostalgia');
  assert.equal(prompts.length, 3);
  const express = require('express');
  const jwt = require('jsonwebtoken');
  const secret = process.env.JWT_ACCESS_SECRET;
  process.env.JWT_ACCESS_SECRET = 'regional-test-secret';
  t.after(() => { if (secret === undefined) delete process.env.JWT_ACCESS_SECRET; else process.env.JWT_ACCESS_SECRET = secret; });
  delete require.cache[require.resolve('../routes/chartRoutes')];
  const app = express();
  app.use('/api', require('../routes/chartRoutes'));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const options = { headers: { Authorization: `Bearer ${jwt.sign({ userId: '507f1f77bcf86cd799439011' }, process.env.JWT_ACCESS_SECRET)}` } };
  const base = `http://127.0.0.1:${server.address().port}/api/local-charts`;
  const vn = await (await fetch(`${base}?countryCode=VN&city=Hanoi&mode=popular`, options)).json();
  const jp = await (await fetch(`${base}?countryCode=JP&city=Tokyo&mode=popular`, options)).json();
  assert.equal(vn.countryCode, 'VN');
  assert.equal(jp.countryCode, 'JP');
  assert.notDeepEqual(vn.songs, jp.songs);
  assert.equal(jp.kind, 'regional');
});
